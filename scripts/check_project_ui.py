from pathlib import Path
import threading
from werkzeug.serving import make_server
from demo_web.app import create_app
from demo_web.seed import seed
from playwright.sync_api import sync_playwright, expect

out = Path('artifacts/project-ui')
out.mkdir(exist_ok=True)
seed(out / 'demo.db')
server = make_server('127.0.0.1', 0, create_app(out / 'demo.db', testing=True))
thread = threading.Thread(target=server.serve_forever, daemon=True)
thread.start()
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        page = b.new_page(viewport={'width': 1440, 'height': 1000})
        page.goto('http://127.0.0.1:8503')
        expect(page.get_by_role('heading', name='프로젝트', exact=True)).to_be_visible(timeout=30000)
        page.get_by_role('button', name='＋ 새 프로젝트', exact=True).click()
        page.get_by_label('프로젝트 이름', exact=True).fill('로그인 웹페이지')
        page.get_by_label('검사할 웹페이지 URL').fill(f'http://127.0.0.1:{server.server_port}/login')
        page.get_by_label('전체 요구사항', exact=True).fill('로그인 페이지가 정상적으로 표시된다.')
        page.get_by_label('전체 예외사항', exact=True).fill('빈 입력은 로그인 요청을 전송하지 않는다.')
        page.get_by_role('button', name='프로젝트 만들기', exact=True).click()
        expect(page.get_by_role('heading', name='요구사항', exact=True).first).to_be_visible()
        page.get_by_role('button', name='＋ 추가', exact=True).click()
        page.get_by_label('이름', exact=True).fill('페이지 접속')
        page.get_by_label('기대 동작', exact=True).fill('로그인 화면이 HTTP 200으로 열린다.')
        page.get_by_label('예외사항', exact=True).fill('서버 오류는 실패로 기록한다.')
        page.get_by_role('button', name='요구사항 추가', exact=True).click()
        page.get_by_role('button', name='테스트 0개 →', exact=True).click()
        page.get_by_role('tab', name='기본 테스트 추가', exact=True).click()
        page.get_by_role('button', name='테스트 추가', exact=True).click()
        expect(page.get_by_text('추가했습니다. 등록된 테스트 탭에서 확인하세요.', exact=True)).to_be_visible()
        page.get_by_test_id('stSidebar').get_by_role('button', name='실행', exact=True).click()
        page.get_by_role('button', name='▶ 테스트 실행', exact=True).click()
        expect(page.get_by_text('실행 완료', exact=True)).to_be_visible(timeout=120000)
        page.get_by_role('button', name='실행 기록 보기 →', exact=True).click()
        expect(page.get_by_test_id('stMetricValue').nth(0)).to_have_text('1')
        expect(page.get_by_test_id('stMetricValue').nth(1)).to_have_text('0')
        expect(page.get_by_test_id('stMetricValue').nth(2)).to_have_text('0')
        page.screenshot(path=str(out / 'history.png'), full_page=True)
        page.get_by_role('tab', name='보고서 다운로드', exact=True).click()
        with page.expect_download() as download:
            page.get_by_role('button', name='보고서 다운로드 · Markdown').click()
        download.value.save_as(str(out / 'downloaded-report.md'))
        page.get_by_test_id('stSidebar').get_by_role('button', name='테스트', exact=True).click()
        page.get_by_role('tab', name='AI로 추가', exact=True).click()
        expect(page.get_by_label('어떤 테스트를 할까요?')).to_be_visible()
        page.get_by_label('어떤 테스트를 할까요?').fill('이메일을 비우면 입력 오류가 표시되는지 확인해줘.')
        page.screenshot(path=str(out / 'ai.png'), full_page=True)
        page.get_by_test_id('stSidebar').get_by_role('button', name='▦  프로젝트', exact=True).click()
        expect(page.get_by_role('heading', name='프로젝트', exact=True)).to_be_visible()
        page.screenshot(path=str(out / 'dashboard.png'), full_page=True)
        page.set_viewport_size({'width': 390, 'height': 844})
        page.screenshot(path=str(out / 'mobile.png'), full_page=True)
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        expect(page.get_by_test_id('stException')).to_have_count(0)
        b.close()
    print('PROJECT UI: create -> requirement -> template -> execute PASS -> history -> download OK')
finally:
    server.shutdown()
    server.server_close()
    thread.join(timeout=5)
