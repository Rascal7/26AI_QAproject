from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import os

out = Path('artifacts/testpilot-preview')
out.mkdir(parents=True, exist_ok=True)
url = os.getenv('QA_PREVIEW_URL', 'http://127.0.0.1:8501')
with sync_playwright() as playwright:
    browser = playwright.chromium.launch()
    page = browser.new_page(viewport={'width': 1440, 'height': 1100}, device_scale_factor=1)
    page.goto(url)
    toolbar = page.locator('.st-key-pilot_topbar')
    expect(page.get_by_role('heading', name='QA 워크스페이스', exact=True)).to_be_visible(timeout=30000)
    expect(page.get_by_role('button', name='기록 보기', exact=True)).to_have_count(5)
    page.screenshot(path=str(out / 'dashboard.png'))
    toolbar.get_by_role('button', name='프로젝트 목록', exact=True).click()
    expect(page.get_by_role('heading', name='프로젝트 목록')).to_be_visible()
    expect(page.locator('.st-key-open_1 button')).to_be_visible()
    page.screenshot(path=str(out / 'projects.png'))
    page.locator('.st-key-open_1 button').click()
    expect(page.get_by_role('heading', name='QA 테스트 요약 및 지표')).to_be_visible()
    page.screenshot(path=str(out / 'requirements.png'))
    page.locator('.st-key-project_nav').get_by_role('button', name='테스트 추가', exact=True).click()
    page.get_by_role('button', name='＋ 테스트 추가', exact=True).click()
    expect(page.get_by_role('dialog').get_by_role('heading', name='AI 테스트 생성')).to_be_visible()
    page.screenshot(path=str(out / 'test-modal.png'))
    page.keyboard.press('Escape')
    toolbar.get_by_role('button', name='실행 기록', exact=True).click()
    expect(page.get_by_role('heading', name='전체 실행 기록')).to_be_visible()
    expect(page.get_by_role('button', name='기록 보기', exact=True).first).to_be_visible()
    page.screenshot(path=str(out / 'history.png'))
    page.get_by_role('button', name='기록 보기', exact=True).first.click()
    expect(page.get_by_role('tab', name='검사 결과', exact=True)).to_be_visible()
    expect(page.get_by_test_id('stException')).to_have_count(0)
    page.close()
    page = browser.new_page(viewport={'width': 390, 'height': 844})
    page.goto(url)
    expect(page.get_by_role('heading', name='QA 워크스페이스', exact=True)).to_be_visible()
    expect(page.get_by_role('button', name='기록 보기', exact=True)).to_have_count(5)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.screenshot(path=str(out / 'mobile.png'))
    browser.close()
print('TestPilot: dashboard, collection, requirements, test dialog, global history, report and mobile OK')
